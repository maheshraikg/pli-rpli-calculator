#!/usr/bin/env python3
"""Generate SAMPLE premium tables so the app can be built before the official
tables arrive. Values are synthetic, not India Post figures. Every file is
written with "isSample": true, which makes the app show the red
"SAMPLE DATA – NOT OFFICIAL" banner.

Only plans whose table layout is known (EA/WLA/AEA) get a sample; Suvidha,
Yugal Suraksha and Bal Jeevan Bima stay without a table until confirmed.

Usage: python3 -I tools/generate_sample_tables.py assets/data/rules_FY2026-27.json assets/data/tables
"""
import json
import sys
from pathlib import Path

UNIT = 10000


def synthetic_monthly(age, term):
    return round(UNIT / (term * 12) * 1.05 + age * 0.4)


def frequencies(monthly):
    return {
        "MONTHLY": monthly,
        "QUARTERLY": round(monthly * 3),
        "HALF_YEARLY": round(monthly * 6 * 0.99),
        "YEARLY": round(monthly * 12 * 0.98),
    }


def build(plan):
    if plan.get("maturityAges"):
        dim, cols = "MATURITY_AGE", plan["maturityAges"]
    elif plan.get("premiumCeasingAges"):
        dim, cols = "PREMIUM_CEASING_AGE", plan["premiumCeasingAges"]
    elif plan.get("terms"):
        dim, cols = "TERM_YEARS", [t["years"] for t in plan["terms"]]
    else:
        return None

    if dim == "TERM_YEARS":
        lo = min(t["entryAge"]["min"] for t in plan["terms"])
        hi = max(t["entryAge"]["max"] for t in plan["terms"])
    else:
        lo, hi = plan["entryAge"]["min"], plan["entryAge"]["max"]
    min_term = plan.get("minTermYears") or 1

    premiums = {f: {} for f in ("MONTHLY", "QUARTERLY", "HALF_YEARLY", "YEARLY")}
    for age in range(lo, hi + 1):
        row = {f: [] for f in premiums}
        for col in cols:
            if dim == "TERM_YEARS":
                term = next(t for t in plan["terms"] if t["years"] == col)
                ok = term["entryAge"]["min"] <= age <= term["entryAge"]["max"]
                years = col
            else:
                years = col - age
                ok = years >= min_term
            values = frequencies(synthetic_monthly(age, years)) if ok else dict.fromkeys(premiums)
            for f in premiums:
                row[f].append(values[f])
        for f in premiums:
            premiums[f][str(age)] = row[f]

    return {
        "schemaVersion": 1,
        "tableId": plan["premiumTableId"],
        "planId": plan["id"],
        "isSample": True,
        "source": "SAMPLE DATA – NOT OFFICIAL. Synthetic values generated by tools/generate_sample_tables.py",
        "unitSumAssured": UNIT,
        "columnDimension": dim,
        "columns": cols,
        "monotonicExceptions": [],
        "premiums": premiums,
    }


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    rules = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    out = Path(argv[2])
    out.mkdir(parents=True, exist_ok=True)
    for plan in rules["plans"]:
        if not plan.get("premiumTableId"):
            continue
        dest = out / f"{plan['premiumTableId']}.json"
        if dest.exists() and not json.loads(dest.read_text(encoding="utf-8")).get("isSample"):
            print(f"SKIP {dest.name}: official table present, not overwriting")
            continue
        table = build(plan)
        if table is None:
            continue
        dest.write_text(json.dumps(table, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"SAMPLE {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

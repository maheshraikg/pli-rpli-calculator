#!/usr/bin/env python3
"""Generate lib/core/app_icons.dart: only the Phosphor icons the app uses,
as const IconData over the bundled Phosphor fonts (assets/fonts/phosphor).

Usage: python3 -I tools/make_app_icons.py <path to phosphor_flutter-2.x/lib/src>
Run after adding an AppIcons.<name> reference anywhere in lib/.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1])
STYLES = {'': 'duotone', 'Line': 'regular', 'Bold': 'bold', 'Fill': 'fill'}
FAMILY = {'duotone': 'PhosphorDuotone', 'regular': 'PhosphorRegular', 'bold': 'PhosphorBold', 'fill': 'PhosphorFill'}

used = set()
for f in (ROOT / 'lib').rglob('*.dart'):
    used |= set(re.findall(r'\bAppIcons\.([a-zA-Z0-9]+)', f.read_text()))

out = []
duo = []
for name in sorted(used):
    suffix = next((s for s in ('Line', 'Bold', 'Fill') if name.endswith(s)), '')
    base = name[: len(name) - len(suffix)] if suffix else name
    style = STYLES[suffix]
    text = (SRC / f'phosphor_icons_{style}.dart').read_text()
    m = re.search(rf'static const {base} = \w+\(\s*(0x[0-9a-f]+)(?:,\s*PhosphorIconData\((0x[0-9a-f]+))?', text)
    if not m:
        sys.exit(f'{base} not found in {style}')
    cp = int(m.group(1), 16)
    if style == 'duotone':
        duo.append(f"  0x{cp:x}: IconData({m.group(2)}, fontFamily: 'PhosphorDuotone'),")
    out.append(f"  static const {name} = IconData(0x{cp:x}, fontFamily: '{FAMILY[style]}');")

(ROOT / 'lib/core/app_icons.dart').write_text(f'''// GENERATED by tools/make_app_icons.py — do not edit by hand.
// Phosphor Icons (https://phosphoricons.com), MIT licence: assets/fonts/phosphor/LICENSE.
import 'package:flutter/widgets.dart';

/// Icons used in the app. Plain names are two-tone (duotone, drawn with
/// [AppIcon]); `…Line`, `…Bold` and `…Fill` are single-colour weights.
abstract final class AppIcons {{
{chr(10).join(out)}
}}

/// Second (lighter) layer of each duotone icon. Const so release builds can
/// tree-shake the icon fonts.
const _duotoneLayer = <int, IconData>{{
{chr(10).join(duo)}
}};

/// Draws any icon; Phosphor duotone icons get their lighter second layer
/// underneath.
class AppIcon extends StatelessWidget {{
  const AppIcon(this.icon, {{super.key, this.size, this.color, this.semanticLabel}});

  final IconData? icon;
  final double? size;
  final Color? color;
  final String? semanticLabel;

  @override
  Widget build(BuildContext context) {{
    final i = icon;
    final layer = i?.fontFamily == 'PhosphorDuotone' ? _duotoneLayer[i!.codePoint] : null;
    if (layer == null) {{
      return Icon(i, size: size, color: color, semanticLabel: semanticLabel);
    }}
    return Stack(alignment: Alignment.center, children: [
      Opacity(opacity: 0.25, child: Icon(layer, size: size, color: color)),
      Icon(i, size: size, color: color, semanticLabel: semanticLabel),
    ]);
  }}
}}
''')
print(f'{len(out)} icons')
